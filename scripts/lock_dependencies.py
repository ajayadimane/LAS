#!/usr/bin/env python
"""Regenerate requirements.txt and requirements-dev.txt from pyproject.toml.

Run this after changing a dependency range in pyproject.toml, then commit the
pyproject change and both lock files together.

    python scripts/lock_dependencies.py

What it produces: every package pinned to one version, each with the sha256 of
*every* artifact published for that version, so the lock installs on any
platform and pip verifies each download.

How it resolves: by default it reuses the versions already installed in the
current environment as constraints, so the result is exactly the set the test
suite is green on. Pass --fresh to resolve from scratch instead; be warned
that resolving broad ranges with hashes can take a very long time.

`pip-compile --generate-hashes` produces an equivalent file and is the more
standard tool, but its resolver did not finish in a reasonable time against
this project's ranges, which is why this script exists.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    import tomli as tomllib

ROOT = Path(__file__).resolve().parents[1]
PYPROJECT = ROOT / "pyproject.toml"

HEADER = [
    "This file is autogenerated. DO NOT EDIT BY HAND.",
    "Regenerate: python scripts/lock_dependencies.py",
    "",
    "Every pin carries the sha256 of every artifact published for that",
    "version, so the lock is valid on any platform and pip verifies each",
    "download. Install with:",
    "    pip install --require-hashes -r <this file>",
]

# Nothing is filtered out of the resolved set: in --require-hashes mode pip
# demands that *every* transitive requirement is pinned, so dropping even
# "plumbing" like wheel breaks the install.
EXCLUDE: set[str] = set()


def _normalise(name: str) -> str:
    """PEP 503 canonical name, so the lock is stable whatever metadata says."""
    return re.sub(r"[-_.]+", "-", name).lower()


def current_versions() -> dict[str, str]:
    out = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    pins = {}
    for line in out.splitlines():
        if "==" not in line or line.startswith("#"):
            continue
        name, _, version = line.partition("==")
        if _normalise(name) not in EXCLUDE:
            pins[_normalise(name)] = version.strip()
    return pins


def resolve(requirements: list[str], constraints: Path | None, tag: str) -> dict:
    """Ask pip what it would install, without installing anything."""
    report = Path(
        subprocess.run(
            ["mktemp", "--suffix", f"-{tag}.json"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
    )
    cmd = [
        sys.executable,
        "-m",
        "pip",
        "install",
        "--dry-run",
        "--quiet",
        "--ignore-installed",
        "--report",
        str(report),
        *requirements,
    ]
    if constraints:
        cmd += ["--constraint", str(constraints)]
    subprocess.run(cmd, check=True, capture_output=True)
    data = json.loads(report.read_text())
    report.unlink(missing_ok=True)
    return {
        _normalise(item["metadata"]["name"]): item["metadata"]["version"]
        for item in data["install"]
        if _normalise(item["metadata"]["name"]) not in EXCLUDE
    }


def artifact_hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        data = json.load(response)
    digests = sorted({u["digests"]["sha256"] for u in data["urls"]})
    if not digests:
        raise SystemExit(f"No published artifacts for {name}=={version}")
    return digests


def write_lock(path: Path, pins: dict[str, str], scope: str) -> None:
    lines = [f"# {line}".rstrip() for line in (*HEADER, "", f"Scope: {scope}.")]
    lines.append("")
    for name in sorted(pins):
        digests = artifact_hashes(name, pins[name])
        entry = f"{name}=={pins[name]} \\\n"
        entry += " \\\n".join(f"    --hash=sha256:{d}" for d in digests)
        lines.append(entry)
    path.write_text("\n".join(lines) + "\n")
    print(f"  {path.name}: {len(pins)} packages pinned")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--fresh",
        action="store_true",
        help="resolve from scratch instead of reusing installed versions "
        "(slow: broad ranges cause heavy backtracking)",
    )
    args = parser.parse_args()

    project = tomllib.loads(PYPROJECT.read_text())["project"]
    runtime = project["dependencies"]
    dev = project["optional-dependencies"]["dev"]

    constraints = None
    if not args.fresh:
        constraints = Path(
            subprocess.run(
                ["mktemp", "--suffix", "-constraints.txt"],
                check=True,
                capture_output=True,
                text=True,
            ).stdout.strip()
        )
        constraints.write_text(
            "\n".join(f"{n}=={v}" for n, v in current_versions().items()) + "\n"
        )
        print(f"  constraining to {len(current_versions())} installed versions")

    print("Resolving...")
    write_lock(
        ROOT / "requirements.txt", resolve(runtime, constraints, "rt"), "runtime only"
    )
    write_lock(
        ROOT / "requirements-dev.txt",
        resolve(runtime + dev, constraints, "dev"),
        "runtime + dev",
    )

    if constraints:
        constraints.unlink(missing_ok=True)
    print("Done. Commit pyproject.toml and both lock files together.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
